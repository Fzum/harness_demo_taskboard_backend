-- Tasks, from the Taskboard (SOURCE TASKBOARD) and from the IBM host (SOURCE HOST).
-- HOST_ID is the task's key on the host (TSK-ID); only the datasync writes it.
CREATE TABLE TASK (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE       VARCHAR(40)   NOT NULL,
    DESCRIPTION VARCHAR(200),
    STATUS      VARCHAR(20)   NOT NULL,
    ASSIGNEE    VARCHAR(8),
    DUE_DATE    DATE,
    SOURCE      VARCHAR(10)   NOT NULL,
    HOST_ID     VARCHAR(10),
    CREATED_AT  TIMESTAMP     NOT NULL,
    UPDATED_AT  TIMESTAMP     NOT NULL
);
CREATE INDEX IX_TASK_HOST_ID ON TASK (HOST_ID);
