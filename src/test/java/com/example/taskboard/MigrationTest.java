package com.example.taskboard;

import static org.assertj.core.api.Assertions.assertThat;

import java.util.List;
import org.flywaydb.core.Flyway;
import org.flywaydb.core.api.output.MigrateResult;
import org.h2.Driver;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SimpleDriverDataSource;

/**
 * The Flyway migrations on a fresh H2 database in DB2 mode: they create the shared schema of the
 * Taskboard, on which the datasync relies, exactly.
 */
class MigrationTest {

  private final SimpleDriverDataSource dataSource =
      new SimpleDriverDataSource(
          new Driver(), "jdbc:h2:mem:migration-test;MODE=DB2;DB_CLOSE_DELAY=-1", "sa", "");
  private final JdbcTemplate jdbc = new JdbcTemplate(dataSource);

  @Test
  void migrationsCreateTheSharedSchemaOnH2InDb2Mode() {
    MigrateResult result = Flyway.configure().dataSource(dataSource).load().migrate();

    assertThat(result.success).isTrue();
    assertThat(result.migrations)
        .extracting(migration -> migration.version)
        .containsExactly("1", "2", "3");
    assertThat(setting("MODE")).isEqualTo("DB2");
    assertThat(columnsOf("TASK"))
        .containsExactly(
            "ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY",
            "TITLE VARCHAR(40) NOT NULL",
            "DESCRIPTION VARCHAR(200)",
            "STATUS VARCHAR(20) NOT NULL",
            "ASSIGNEE VARCHAR(8)",
            "DUE_DATE DATE",
            "SOURCE VARCHAR(10) NOT NULL",
            "HOST_ID VARCHAR(10)",
            "CREATED_AT TIMESTAMP NOT NULL",
            "UPDATED_AT TIMESTAMP NOT NULL",
            "PRIORITY VARCHAR(10) DEFAULT 'MEDIUM' NOT NULL");
    assertThat(columnsOf("OUTBOX_EVENT"))
        .containsExactly(
            "ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY",
            "AGGREGATE_TYPE VARCHAR(30) NOT NULL",
            "AGGREGATE_ID BIGINT NOT NULL",
            "EVENT_TYPE VARCHAR(30) NOT NULL",
            "PAYLOAD VARCHAR(4000) NOT NULL",
            "STATUS VARCHAR(20) DEFAULT 'PENDING' NOT NULL",
            "ATTEMPTS INTEGER DEFAULT 0 NOT NULL",
            "LAST_ERROR VARCHAR(1000)",
            "CREATED_AT TIMESTAMP NOT NULL",
            "PROCESSED_AT TIMESTAMP");
    assertThat(primaryKeyOf("TASK")).isEqualTo("ID");
    assertThat(primaryKeyOf("OUTBOX_EVENT")).isEqualTo("ID");
    assertThat(indexes())
        .containsExactlyInAnyOrder(
            "IX_TASK_HOST_ID ON TASK (HOST_ID)",
            "IX_OUTBOX_EVENT_STATUS ON OUTBOX_EVENT (STATUS, ID)",
            "IX_OUTBOX_EVENT_AGGREGATE ON OUTBOX_EVENT (AGGREGATE_ID, ID)");
  }

  private String setting(String name) {
    return jdbc.queryForObject(
        "SELECT SETTING_VALUE FROM INFORMATION_SCHEMA.SETTINGS WHERE SETTING_NAME = ?",
        String.class,
        name);
  }

  /** Each column as in the DDL: name, type, default, nullability, identity. */
  private List<String> columnsOf(String table) {
    return jdbc.query(
        """
        SELECT * FROM INFORMATION_SCHEMA.COLUMNS
        WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ? ORDER BY ORDINAL_POSITION""",
        (rs, row) -> {
          String type = rs.getString("DATA_TYPE");
          if (type.equals("CHARACTER VARYING")) {
            type = "VARCHAR(" + rs.getInt("CHARACTER_MAXIMUM_LENGTH") + ")";
          }
          StringBuilder column = new StringBuilder(rs.getString("COLUMN_NAME") + " " + type);
          if (rs.getString("COLUMN_DEFAULT") != null) {
            column.append(" DEFAULT ").append(rs.getString("COLUMN_DEFAULT"));
          }
          if (rs.getString("IS_NULLABLE").equals("NO")) {
            column.append(" NOT NULL");
          }
          if (rs.getString("IS_IDENTITY").equals("YES")) {
            column.append(" GENERATED ").append(rs.getString("IDENTITY_GENERATION"));
            column.append(" AS IDENTITY");
          }
          return column.toString();
        },
        table);
  }

  private String primaryKeyOf(String table) {
    return jdbc.queryForObject(
        """
        SELECT K.COLUMN_NAME
        FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS C
        JOIN INFORMATION_SCHEMA.KEY_COLUMN_USAGE K ON K.CONSTRAINT_NAME = C.CONSTRAINT_NAME
        WHERE C.TABLE_NAME = ? AND C.CONSTRAINT_TYPE = 'PRIMARY KEY'""",
        String.class,
        table);
  }

  /** The indexes the migrations create, as in their CREATE INDEX statements. */
  private List<String> indexes() {
    return jdbc.queryForList(
        """
        SELECT INDEX_NAME || ' ON ' || TABLE_NAME || ' ('
               || LISTAGG(COLUMN_NAME, ', ') WITHIN GROUP (ORDER BY ORDINAL_POSITION) || ')'
        FROM INFORMATION_SCHEMA.INDEX_COLUMNS
        WHERE TABLE_SCHEMA = 'PUBLIC' AND INDEX_NAME LIKE 'IX_%'
        GROUP BY INDEX_NAME, TABLE_NAME""",
        String.class);
  }
}
