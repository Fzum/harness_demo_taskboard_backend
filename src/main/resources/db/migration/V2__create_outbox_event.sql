-- The transactional outbox: the backend inserts one event per task change, in the transaction of
-- the change; the datasync relays the events to the host and owns STATUS, ATTEMPTS, LAST_ERROR
-- and PROCESSED_AT.
CREATE TABLE OUTBOX_EVENT (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    AGGREGATE_TYPE VARCHAR(30)   NOT NULL,
    AGGREGATE_ID   BIGINT        NOT NULL,
    EVENT_TYPE     VARCHAR(30)   NOT NULL,
    PAYLOAD        VARCHAR(4000) NOT NULL,
    STATUS         VARCHAR(20)   DEFAULT 'PENDING' NOT NULL,
    ATTEMPTS       INTEGER       DEFAULT 0 NOT NULL,
    LAST_ERROR     VARCHAR(1000),
    CREATED_AT     TIMESTAMP     NOT NULL,
    PROCESSED_AT   TIMESTAMP
);
CREATE INDEX IX_OUTBOX_EVENT_STATUS ON OUTBOX_EVENT (STATUS, ID);
CREATE INDEX IX_OUTBOX_EVENT_AGGREGATE ON OUTBOX_EVENT (AGGREGATE_ID, ID);
